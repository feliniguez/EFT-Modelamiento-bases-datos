
-- INFORME 1: Asociaciones profesionales creadas después del año 2000
SELECT
    COD_ASOCIACION,
    DBMS_LOB.SUBSTR(NOMBRE, 100, 1) AS NOMBRE,
    FECHA_CREACION,
    DBMS_LOB.SUBSTR(TIPO, 10, 1) AS TIPO
FROM ASOCIACION
WHERE DBMS_LOB.SUBSTR(TIPO, 10, 1) = 'P'
  AND FECHA_CREACION > DATE '2000-12-31'
ORDER BY FECHA_CREACION DESC;



-- INFORME 2: Clubes con la letra 'a' y patrimonio superior a 200 millones
-- Conversión referencial: 955 CLP por USD

SELECT
    COD_CLUB,
    DBMS_LOB.SUBSTR(NOMBRE, 100, 1) AS NOMBRE,
    PATRIMONIO AS PATRIMONIO_CLP,
    ROUND(PATRIMONIO / 955, 2) AS PATRIMONIO_USD
FROM CLUB
WHERE LOWER(DBMS_LOB.SUBSTR(NOMBRE, 100, 1)) LIKE '%a%'
  AND PATRIMONIO > 200000000
ORDER BY COD_CLUB DESC;
